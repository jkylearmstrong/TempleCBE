test_that("tbl_longitudinal_cox_screen matches a hand-built coxph on the per-subject summaries", {
  set.seed(11)
  n <- 60
  d <- data.frame(id = rep(seq_len(n), each = 4), t = rep(c(0, 5, 15, 30), n))
  d$hr <- rnorm(nrow(d), 80, 10)
  st <- rbinom(n, 1, 0.6)
  d$status <- rep(st, each = 4)
  res <- tbl_longitudinal_cox_screen(d, "id", "t", "status", "hr")
  expect_equal(res$metric, c("pct_change_directional", "variance", "excursion", "sd"))
  expect_true(all(res$status == "ok"))
  sdv <- tapply(d$hr, d$id, sd)
  fit <- survival::coxph(survival::Surv(rep(30, n), st) ~ sdv)
  expect_equal(res$hr[res$metric == "sd"], unname(exp(coef(fit))), tolerance = 1e-8)
  expect_equal(res$events[1], sum(st))
  md <- data.frame(columns = "hr", labels = "Heart rate", domain = "CV")
  res2 <- tbl_longitudinal_cox_screen(d, "id", "t", "status", "hr", metrics = "excursion", metadata = md)
  expect_equal(res2$label, "Heart rate")
  expect_equal(res2$domain, "CV")
  expect_equal(names(res2)[1:4], c("feature", "label", "domain", "metric"))
})

