test_that("tbl_domain_correlations splits within and between domain pairs", {
  set.seed(4)
  a <- rnorm(80)
  d <- data.frame(a1 = a, a2 = a + rnorm(80, 0, 0.1), b1 = a + rnorm(80, 0, 0.2), b2 = rnorm(80), c1 = rnorm(80))
  map <- c(a1 = "A", a2 = "A", b1 = "B", b2 = "B", c1 = "C")
  res <- tbl_domain_correlations(d, map, cutoff = 0.8)
  expect_true(all(abs(res$correlation) >= 0.8))
  expect_equal(res$correlation[res$feature_1 == "a1" & res$feature_2 == "a2"], cor(d$a1, d$a2))
  expect_equal(res$scope[res$feature_1 == "a1" & res$feature_2 == "a2"], "within")
  expect_equal(res$scope[res$feature_1 == "a1" & res$feature_2 == "b1"], "between")
  expect_equal(res$n[1], 80L)
  expect_false(is.unsorted(rev(abs(res$correlation))))
  x <- tbl_domain_correlations(d, map, cutoff = 0.8, cross_domain_only = TRUE)
  expect_true(all(x$scope == "between"))
  expect_equal(sum(attr(res, "domain_summary")$n_pairs), nrow(res))
  df_map <- data.frame(variable = names(map), domain = unname(map))
  expect_equal(tbl_domain_correlations(d, df_map, cutoff = 0.8, method = "spearman")$scope[1], "within")
  none <- tbl_domain_correlations(d, map, cutoff = 1)
  expect_equal(nrow(none), 0L)
  expect_equal(nrow(attr(none, "domain_summary")), 0L)
  expect_error(tbl_domain_correlations(d, c(a1 = "A", zz = "B")), "not in")
  expect_error(tbl_domain_correlations(d, c(a1 = "A")), "at least two")
  expect_error(tbl_domain_correlations(d, 1:3), "named vector")
  expect_error(tbl_domain_correlations(d, data.frame(x = 1)), "needs columns")
  expect_error(tbl_domain_correlations(d, map, cutoff = 2), "cutoff")
  expect_error(tbl_domain_correlations(d, c(a1 = "A", a1 = "B")), "more than one")
  d$s <- "x"
  expect_error(tbl_domain_correlations(d, c(a1 = "A", s = "B")), "Non-numeric")
})

test_that("batch_glm_single reproduces glm_single, ranks and adds dy/dx", {
  res <- batch_glm_single(mtcars, c("wt", "hp", "disp"), c("mpg", "qsec"))
  expect_equal(nrow(res), 6L)
  one <- glm_single(mtcars, "mpg", "wt")
  r <- res[res$output == "mpg" & res$input == "wt", ]
  expect_equal(r$estimate, one$estimate[one$scale == "normalized"])
  expect_equal(r$estimate_dy_dx, one$estimate[one$scale == "raw"])
  expect_equal(r$p.value_dy_dx, r$p.value, tolerance = 1e-8)
  mp <- res[res$output == "mpg", ]
  expect_equal(mp$rank[order(-abs(mp$estimate))], 1:3)
  expect_equal(res$p.adj, p.adjust(res$p.value, "BH")[match(paste(res$output, res$input), paste(res$output, res$input))] )
  expect_true(all(res$significance %in% c("***", "**", "*", "ns")))
  raw <- batch_glm_single(mtcars, "wt", "mpg", normalize = FALSE)
  expect_equal(raw$estimate, one$estimate[one$scale == "raw"])
  expect_false("estimate_dy_dx" %in% names(raw))
  nodydx <- batch_glm_single(mtcars, "wt", "mpg", include_dy_dx = FALSE)
  expect_false("estimate_dy_dx" %in% names(nodydx))
  bin <- batch_glm_single(mtcars, c("wt", "hp"), "am", family = binomial())
  expect_equal(nrow(bin), 2L)
  self <- batch_glm_single(mtcars, c("wt", "mpg"), "mpg")
