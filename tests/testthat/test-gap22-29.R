test_that("compute_longitudinal_composite_index anchors on baseline mean and SD with polarities", {
  set.seed(3)
  d <- expand.grid(id = 1:30, time = c(0, 5, 15))
  d$a <- rnorm(90, 10 + d$time / 5, 2)
  d$b <- rnorm(90, 50 - d$time, 5)
  map <- data.frame(variable = "b", alpha = -1)
  out <- compute_longitudinal_composite_index(d, c("a", "b"), map, id_col = "id")
  b0 <- d[d$time == 0, ]
  za <- (d$a - mean(b0$a)) / sd(b0$a)
  zb <- -(d$b - mean(b0$b)) / sd(b0$b)
  expect_equal(out$composite_index, (za + zb) / 2)
  expect_equal(mean(out$composite_index[out$time == 0]), 0, tolerance = 1e-12)
  expect_equal(attr(out, "baseline")$alpha, c(1, -1))
  expect_equal(attr(out, "baseline")$n0, c(30L, 30L))
  # missing component: index uses the other variable
  d$b[1] <- NA
  o2 <- compute_longitudinal_composite_index(d, c("a", "b"), id_col = "id", index_name = "idx")
  expect_equal(o2$idx[1], (d$a[1] - mean(b0$a)) / sd(b0$a))
  o3 <- compute_longitudinal_composite_index(d, c("a", "b"), id_col = "id", min_vars = 2)
  expect_true(is.na(o3$composite_index[1]))
})

