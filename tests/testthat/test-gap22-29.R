test_that("tbl_landmark_cutpoints restarts the clock and matches survival::coxph", {
  set.seed(5)
  n <- 300
  x <- rnorm(n)
  tm <- rexp(n, 0.02 * exp(0.6 * x))
  d <- data.frame(time = tm, status = rbinom(n, 1, 0.8), x = x)
  res <- tbl_landmark_cutpoints(d, "x", "time", "status", landmarks = c(10, 30), method = "median")
  expect_equal(res$landmark, c(10, 30))
  expect_true(all(res$status == "ok"))
  at <- d[d$time > 10, ]
  expect_equal(res$n[1], nrow(at))
  cut <- median(at$x)
  fit <- survival::coxph(survival::Surv(time - 10, status) ~ I(x > cut), data = at)
  expect_equal(res$hr[1], unname(exp(coef(fit))), tolerance = 1e-8)
  expect_equal(res$cutpoint[1], cut)
  expect_equal(res$n_low[1] + res$n_high[1], res$n[1])
  q <- tbl_landmark_cutpoints(d, "x", "time", "status", landmarks = 10, method = "quantile", probs = 0.8)
  expect_equal(q$cutpoint, unname(quantile(at$x, 0.8)))
  sc <- tbl_landmark_cutpoints(d, "x", "time", "status", landmarks = 10)
  expect_equal(sc$status, "ok")
  expect_true(sc$p.value >= 0 && sc$p.value <= 1)
  late <- tbl_landmark_cutpoints(d, "x", "time", "status", landmarks = 1e6, method = "median")
  expect_match(late$status, "too few")
})

