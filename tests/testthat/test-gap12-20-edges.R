test_that("piecewise LMM reports bad input, failed knots, new subjects and missing times", {
  skip_if_not_installed("lme4")
  set.seed(7)
  d <- expand.grid(id = 1:15, time = 0:6)
  d$y <- 5 + rnorm(15)[d$id] + d$time - 2 * pmax(d$time - 3, 0) + rnorm(nrow(d), 0, 0.3)
  tuned <- tune_breakpoint_lmm(d, "y", "time", "id", knots = c(3, 50), metric = "BIC")
  expect_equal(tuned$status[tuned$knot == 50], "no observations on one side of the knot")
  expect_true(is.na(tuned$AIC[tuned$knot == 50]))
  expect_true(tuned$selected[tuned$knot == 3])
  auto <- tune_breakpoint_lmm(d, "y", "time", "id")
  expect_equal(sort(auto$knot), 1:5)
  expect_error(tune_breakpoint_lmm(d, "y", "time", "id", knots = numeric(0)), "knots")
  expect_error(tune_breakpoint_lmm(d[1:2, ], "y", "time", "id"), "at least 3")
  expect_error(tune_breakpoint_lmm(as.list(d), "y", "time", "id"), "data frame")
  dn <- d
  dn$y <- as.character(dn$y)
  expect_error(tune_breakpoint_lmm(dn, "y", "time", "id"), "numeric")

  d$y[c(3, 40)] <- NA
  d$time[41] <- NA
  d$y[41] <- NA
  d$id <- as.character(d$id)
  extra <- data.frame(id = "new", time = 2, y = NA)
  imp <- impute_piecewise_lmm(rbind(d, extra), "y", "time", "id") # knot picked by AIC
  expect_true(all(imp$y_was_imputed[c(3, 40, nrow(imp))]))
  expect_false(anyNA(imp$y_imputed[c(3, 40, nrow(imp))]))
  expect_true(is.na(imp$y_imputed[41]))
  expect_false(imp$y_was_imputed[41])
  expect_error(impute_piecewise_lmm(d, "y", "time", "id", knot = "a"), "single number")
  expect_error(impute_piecewise_lmm(d, "y", "time", "id", knot = 99), "failed at knot")
})

