test_that("tbl_tuning_by_quantile maps legacy columns and handles bare terms", {
  legacy <- data.frame(ibs = c(0.3, 0.1, 0.2, NA, 0.25, 0.15), alphas = 1:6 / 10)
  s <- tbl_tuning_by_quantile(legacy, n_tiles = 2)
