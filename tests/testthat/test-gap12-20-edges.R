test_that("tbl_contingency_2x2 percent bases, chisq only, no totals, tiny p-values", {
  d <- data.frame(g = rep(c("a", "b"), each = 100), o = c(rep(c("y", "n"), c(90, 10)), rep(c("y", "n"), c(10, 90))))
  col <- tbl_contingency_2x2(d, "g", "o", percent = "col", test = "chisq")
  expect_equal(col$table$n[1], "10 (10.0%)")
  expect_equal(col$table$Total[3], "200 (100.0%)")
  expect_equal(nrow(col$tests), 1L)
  expect_equal(col$tests$p_formatted, "<0.001")
  tot <- tbl_contingency_2x2(d, "g", "o", percent = "total", include_total = FALSE, note = FALSE, p_digits = 2)
  expect_equal(tot$table$n[1], "10 (5.0%)")
  expect_false("Total" %in% names(tot$table))
  expect_null(tot$note)
  expect_error(tbl_contingency_2x2(list(), "g", "o"), "data frame")
  expect_error(tbl_contingency_2x2(d, "g", "o", conf.level = 2), "conf.level")
})

