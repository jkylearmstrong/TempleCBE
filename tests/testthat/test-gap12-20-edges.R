test_that("tbl_correlated_pairs supports spearman, gt output and argument checks", {
  set.seed(2)
  a <- rnorm(40)
  d <- data.frame(a = a, b = a^3, c = rnorm(40), s = letters[rep(1:4, 10)])
  sp <- tbl_correlated_pairs(d, cutoff = 0.99, method = "spearman", format = "tibble")
  expect_equal(nrow(sp), 1L)
  expect_equal(sp$correlation, 1)
  expect_match(attr(sp, "caption"), "spearman")
  expect_error(tbl_correlated_pairs(d, c("a", "zz"), format = "tibble"), "not in")
  expect_error(tbl_correlated_pairs(d, c("a", "s"), format = "tibble"), "Non-numeric")
  expect_error(tbl_correlated_pairs(d, format = "tibble", metadata = data.frame(x = 1)), "metadata")
  expect_error(tbl_correlated_pairs(1, format = "tibble"), "data frame")
  skip_if_not_installed("gt")
  expect_s3_class(tbl_correlated_pairs(d, cutoff = 0.9, format = "gt"), "gt_tbl")
  skip_if_not_installed("knitr")
  expect_s3_class(tbl_correlated_pairs(d, cutoff = 0.9, caption = FALSE), "knitr_kable")
})

test_that("inspect_rank_deficiency handles glm fits and rejects multivariate fits", {
  d <- data.frame(y = c(0, 1, 0, 1, 1, 0, 1, 1), a = 1:8, b = 2 * (1:8))
  g <- suppressWarnings(glm(y ~ a + b, binomial, d))
  r <- inspect_rank_deficiency(g, verbose = FALSE)
  expect_equal(r$dropped, "b")
  expect_match(r$message, "Rank-deficient")
  expect_s3_class(r, "cbe_rank_deficiency")
  expect_error(inspect_rank_deficiency(lm(cbind(y, a) ~ b, d)), "Multivariate")
})

